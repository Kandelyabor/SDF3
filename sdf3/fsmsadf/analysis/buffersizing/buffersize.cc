int BufferSizingScenarioUsingMaxPlus::nrThroughputCalls = 0;

void BufferSizingScenarioUsingMaxPlus::initialize() {
    initMaxThroughput(*g);
    // std::cout << "thrMax = " << maxThroughput << std::endl;
    // add capacity channels to scenario graphs
    // create fsmsadf buffers

    ScenarioGraphs& scGraphs = g->getScenarioGraphs();

    int bufferId = 0;
    for (const auto& sceGraph : scGraphs) {
        const Channels& chs = sceGraph->getChannels();
        for (const auto& ch : chs) {
            if (ch->getType() == "buffer") {
                Actor *srcActor = ch->getSrcActor();
                Actor *dstActor = ch->getDstActor();

                ChannelRef capacityChannel = sceGraph->createChannel(dstActor, // NOLINT(*suspicious-call-argument)
                                                                   srcActor,
                                                                   ch->getDstPort()->getRate(),
                                                                   ch->getSrcPort()->getRate(),
                                                                   ch->getName() + "_d");
                capacityChannel->isCapacityChannel = true;

                auto b = std::make_unique<Buffer>();
                b->id = bufferId;
                bufferId++;
                b->bufferChannel = ch.get();
                b->capacityChannel = capacityChannel;
                this->fsmsadfBuffers.insertBuffer(std::move(b));

                // add dummy buffers to all other scenario graph

                for (const auto& anotherGraphIter : scGraphs) {
                    if (anotherGraphIter != sceGraph) {
                        GraphComponent c = GraphComponent(
                                sceGraph.get(), static_cast<CId>(sceGraph->getActors().size()));
                        auto a = std::make_unique<Actor>(c);
                        a->setName(CString("dummyAutoGeneratedBufferActor"));

                        Actor::ProcessorType ptype = Actor::ProcessorType("dummy");
                        for (auto sceIter = g->getScenarios().begin();
                             sceIter != g->getScenarios().end();
                             sceIter++) {
                            ptype.executionTime[(*sceIter).get()] = 0;
                            a->setRepetitionsOfScenario(*(*sceIter), 0);
                        }

                        Actor::ProcessorTypes pTypes;
                        pTypes.emplace_back(std::move(ptype));
                        a->setDefaultProcessorType("dummy");
                        a->setProcessorTypes(pTypes);
                        auto* ar = a.get();
                        anotherGraphIter->addActor(std::move(a));
                        ChannelRef dummyChannel = anotherGraphIter->createChannel(
                                ar, ar); // , ch->getDstPort()->getRate(),
                                       // ch->getSrcPort()->getRate(), ch->getName() + "_d");
                        b->dummyBufferChannels.push_back(dummyChannel);
                    }
                }
            }
        }
    }
}

TDtime BufferSizingScenarioUsingMaxPlus::throughputAndCriticalBuffers(
        const ScenarioMatrices &scenarioMatrices,
        std::map<CString, std::unordered_set<int>> &criticalCapacityChannels) const {
    // create a minimal edge labelled scenario automaton
    std::unique_ptr<EdgeLabeledScenarioFSM> elsFSM =
            FSMConverter::minimalEdgeLabeledFSM(*(g->getFSM()));

    MaxPlusAutomatonWithRewardsAndCriticalBuffers fsm;

    // add state for every initial token and location of the fsm

    // create the FSM states for every pair of a state of the FSMSADF's FSM
    // and an initial token
    const ELSSetOfStates &Q = elsFSM->getStates();
    for (const auto& [key, q] : Q) {
        // get the number of initial tokens
        auto &s = dynamic_cast<ELSState &>(*q);
        const auto *e = dynamic_cast<const ELSEdge *>(*(s.getOutgoingEdges().begin()));
        unsigned int nrTokens = scenarioMatrices.at(e->getLabel())->getCols();
        for (unsigned int k = 0; k < nrTokens; k++) {
            // create a state for (q, k)
            CId qId = s.getLabel();
            fsm.addState({qId, static_cast<int>(k)});
        }
    }

    // add the edges. For every edge (q1, q2) in the original fsm,
    // let s be the scenario of q2 and let M_s be the matrix of s
    // For every non -inf element d=M_s(k,m) add an edge from state (q1,k)
    // to (q2,m) labelled with d.

    // for every state of the fsm...
    for (const auto& [key, q] : Q) {
        auto &q1 = dynamic_cast<ELSState &>(*q);
        CId q1Id = q1.getLabel();

        // for every outgoing edge of the state
        const ELSSetOfEdgeRefs &t = q1.getOutgoingEdges();
        for (const auto *e : t) {
            auto tr = dynamic_cast<const ELSEdge &>(*e);
            CId q2Id = (dynamic_cast<ELSStateRef>(tr.getDestination()))->getLabel();
            const CString &sc = tr.getLabel();
            const auto* Ms = dynamic_cast<ExtendedMatrix*>(scenarioMatrices.at(sc).get());

            CDouble rew = g->getScenarioRef(sc)->getReward();

            // for every entry in the matrix
            for (unsigned int r = 0; r < Ms->getRows(); r++) {
                for (unsigned int c = 0; c < Ms->getCols(); c++) {
                    MPDelay d = Ms->get(r, c);
                    std::unordered_set<int> bs = Ms->getBufferSet(r, c);
                    if (!MP_IS_MINUS_INFINITY(d)) {
                        MPARStateBRef src = fsm.getStateLabeled({q1Id, static_cast<int>(c)});
                        MPARStateBRef dst = fsm.getStateLabeled({q2Id, static_cast<int>(r)});
                        fsm.addEdge(*src, {d, sc.c_str(), rew, bs}, *dst);
                    }
                }
            }
        }
    }

    // calculate MCR of the FSM

    MPARCycleB critCycle;
    double mcr = fsm.calculateMCRAndCycle(&critCycle);
    TDtime th = 1.0 / mcr;

    MPARCycleB::const_iterator i = critCycle.begin();
    for (; i != critCycle.end(); i++) {
        const auto *e = static_cast<MPAREdgeBRef>(*i);
        // scenarios->push_back(g->getScenario(*(e->label.scenario)));
        for (auto iter : e->getLabel().bufferSet) {
            criticalCapacityChannels[e->getLabel().mode].insert(iter);
        }
    }

    return th;
}

void BufferSizingScenarioUsingMaxPlus::transformDistributionToInitialTokensOnCapacityChannels(
        StorageDistributionMP& d) const {
    int tokenCounter = 0;
    for (const auto& b : fsmsadfBuffers.getBuffers()) {
        Channel *capCh = b->capacityChannel;

        // reset names
        CStrings pf_tn;
        capCh->setPersistentAndFinalTokenNames(pf_tn);

        capCh->setInitialAndFinalTokens(d.sp[b->id] - b->bufferChannel->getInitialTokens());

        for (unsigned int i = 1; i <= capCh->getInitialTokens(); i++, tokenCounter++) {
            CString tokenName = CString("d_") + CString(tokenCounter);
            capCh->addPersistentTokenName(tokenName);
            capCh->addPersistentFinalTokenName(tokenName);
        }

        for (auto *dummyCh : b->dummyBufferChannels) {
            dummyCh->setPersistentAndFinalTokenNames(capCh->getPersistentTokenNames());
            dummyCh->setInitialAndFinalTokens(capCh->getInitialTokens());
        }
    }
}

std::unique_ptr<ScenarioMatrices> BufferSizingScenarioUsingMaxPlus::computeExtendedMatrixRepresentations() const {
    auto sm = std::make_unique<ScenarioMatrices>();

    Scenarios& scenarios = g->getScenarios();
    for (const auto& sce : scenarios) {
        CStrings persistentTokens;
        CStrings persistentTokensFinal;
        ScenarioGraph *sceGraph = sce->getScenarioGraph();
        PersistentTokenIndexMap mp = sceGraph->getPersistentTokenIndexMap();
        PersistentTokenIndexMap mpf = sceGraph->getPersistentTokenIndexMapFinal();

        // collect names of the initial and final persistent tokens
        for (const auto& [pt_mi, idx] : mp) {
            persistentTokens.push_back(pt_mi);
        }
        for (const auto& [pt_mi, idx] : mpf) {
            persistentTokensFinal.push_back(pt_mi);
        }

        // sort them to get a canonical order
        persistentTokens.sort();
        persistentTokensFinal.sort();

        std::list<uint> tokenIndicesInitial;
        for (const auto &ti : persistentTokens) {
            tokenIndicesInitial.push_back(mp[ti]);
        }
        std::list<uint> tokenIndicesFinal;
        for (const auto &ti : persistentTokensFinal) {
            tokenIndicesFinal.push_back(mpf[ti]);
        }

        auto sg = std::unique_ptr<TimedSDFgraph>(sceGraph->extractSDFgraph(*sce));

        std::unique_ptr<RepetitionVector> partialRepVec = FSMSADF::Graph::getPartialRepetitionVector(*sce);
        auto G = std::make_unique<GraphDecoration::GraphEMR>(*sg, true, partialRepVec.get());
        MaxPlusAnalysis::ExplorationEMR mpe;
        mpe.G = std::move(G);
        mpe.g = sg.get();
        std::unique_ptr<Matrix> matrix = nullptr;
        try {
            matrix = mpe.convertToMaxPlusMatrixForWeakFSMSADF();
        } catch (CDeadlockException &) {
            throw CScenarioDeadlockException("Cannot compute matrix for scenario " + sce->getName()
                                                     + ", because it deadlocks.",
                                             sce.get());
        }
        // create the sub matrix of only the persistent tokens.
        auto sMatrix = matrix->getSubMatrixPtr(tokenIndicesFinal, tokenIndicesInitial);

        (*sm)[sce->getName()] = std::move(sMatrix);
    }
    return sm;
}

/**
 * ThroughputMargin
 * accuracy of throughput comparisons
 */
const double BufferSizingScenarioUsingMaxPlus::ThroughputMargin = 1e-10;

/******************************************************************************
 * Bounds on the search space
 *****************************************************************************/

/**
 * initBoundsSearchSpace ()
 * Compute bounds on the trade-off space that must be explored.
 */
void BufferSizingScenarioUsingMaxPlus::initBoundsSearchSpace() {
    initMinimalChannelSzStep();
    initMinimalChannelSz();
    initLbDistributionSz();
    // initMaxThroughput();
}

/**
 * initMinimalChannelSzStep ()
 * Compute lower bound on the step size of channels
 */
void BufferSizingScenarioUsingMaxPlus::initMinimalChannelSzStep() const {
    for (const auto& b : fsmsadfBuffers.getBuffers()) {
        Channel *ch = b->bufferChannel;

        Port *srcPort = ch->getSrcPort();
        Port *dstPort = ch->getDstPort();
        std::map<const Scenario *, Rate> p = srcPort->getRate();
        std::map<const Scenario *, Rate> c = dstPort->getRate();
        for (auto pIter = p.begin(), cIter = c.begin(); pIter != p.end(); pIter++, cIter++) {
            // std::cout << pIter->first->getName() << std::endl;
            TBufSize s = gcd(pIter->second, cIter->second);
            b->minSzStep[pIter->first] = s;
        }
    }
}

/**
 * initLbDistributionSz ()
 * Compute lower bound on the buffer size needed for positive throughput
 */
void BufferSizingScenarioUsingMaxPlus::initLbDistributionSz() {
    lbDistributionSz = 0;

    for (uint c = 0; c < fsmsadfBuffers.getBuffers().size(); c++) {
        lbDistributionSz += minSz[c];
    }
}

/**
 * checkAgainstMaxThroughput ()
 * Check if throughput th is equal to maximal throughput maxTh up to a relative
 * margin of error equal to 'margin'.
 * Since both are floating point variable comparison with == may fail
 * It is assumed that th <= maxTh
 */
inline bool BufferSizingScenarioUsingMaxPlus::checkAgainstMaxThroughput(double th,
                                                                        double maxTh,
                                                                        double margin) {
    return (th / maxTh) > 1.0 - margin;
}

/**
 * initMaxThroughput ()
 * Compute the maximal throughput that can be achieved by the graph.
 */
void BufferSizingScenarioUsingMaxPlus::initMaxThroughput(const Graph& g) {
    maxThroughput = FSMSADF::throughputAnalysisGraphUsingMaxPlusAutomatonWeaklyConsistent(g);
}

/**
 * initMinimalChannelSz ()
 * Compute lower bound on the buffer size needed for positive throughput
 */
void BufferSizingScenarioUsingMaxPlus::initMinimalChannelSz() {
    minSz = std::make_unique<TBufSize[]>(fsmsadfBuffers.getBuffers().size());
    for (unsigned int i = 0; i < fsmsadfBuffers.getBuffers().size(); i++) {
        minSz[i] = 0;
    }

    for (const auto& b : fsmsadfBuffers.getBuffers()) {
        Channel *ch = b->bufferChannel;

        Port *srcPort = ch->getSrcPort();
        Port *dstPort = ch->getDstPort();
        std::map<const Scenario *, Rate> p = srcPort->getRate();
        std::map<const Scenario *, Rate> c = dstPort->getRate();
        uint t = b->bufferChannel->getInitialTokens();
        uint lbMax = 0;

        if (ch->getSrcActor()->getId() != ch->getDstActor()->getId()) {
            for (auto pIter = p.begin(), cIter = c.begin(); pIter != p.end(); pIter++, cIter++) {
                uint pr = pIter->second;
                uint cr = cIter->second;
                uint lb = pr + cr - gcd(pr, cr) + (t % gcd(pr, cr));
                lb = (lb > t ? lb : t);
                lbMax = (std::max)(lb, lbMax);
            }
        } else {
            for (auto pIter = p.begin(), cIter = c.begin(); pIter != p.end(); pIter++, cIter++) {
                uint pr = pIter->second;
                uint cr = cIter->second;
                uint lb = pr + (cr > t ? cr : t);
                lbMax = (std::max)(lb, lbMax);
            }
        }
        minSz[b->id] = lbMax;
    }
}

