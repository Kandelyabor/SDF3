#ifndef FSMSADF_RESOURCE_ALLOCATION_FLOW_BASE_FLOW_H_INCLUDED
#define FSMSADF_RESOURCE_ALLOCATION_FLOW_BASE_FLOW_H_INCLUDED

#include "fsmsadf/resource_allocation/flow/base_platform/memory/memory.h"
#include "fsmsadf/resource_allocation/flow/base_platform/tile/binding.h"
#include <memory>

namespace FSMSADF {

/**
 * Graph mapping to MP-SoC flow
 */
class SDF3FlowBase {
public:
    // State of the mapping flow
    enum class FlowState {
        FlowStart,
        FlowComputeStorageDist,
        FlowSelectStorageDist,
        FlowEstimateStorageDist,
        FlowEstimateBandwidthConstraint,
        FlowBindGraphToTile,
        FlowEstimateConnectionDelay,
        FlowConstructTileSchedules,
        FlowCompleted,
        FlowFailed
    };

protected:
    // Constructor
    SDF3FlowBase();

public:
    // Destructor
    virtual ~SDF3FlowBase();

    SDF3FlowBase(const SDF3FlowBase&) = delete;
    SDF3FlowBase& operator=(const SDF3FlowBase&) = delete;
    SDF3FlowBase(SDF3FlowBase&&) = delete;
    SDF3FlowBase& operator=(SDF3FlowBase&&) = delete;

    // Construct
    void constructFromXML(CNodePtr sdf3Node);

    // Convert
    void convertToXML( CNodePtr sdf3Node);
    void convertToHTML(const CString &dirname);

    // Execute design flow
    virtual FlowState run();

    ///////////////
    // Accessors //
    ///////////////

    // Run flow step-by-step
    [[nodiscard]] bool getStepMode() const { return stepMode; };
    void setStepMode(bool flag) { stepMode = flag; };

    // Tile binding and scheduling algorithm
    [[nodiscard]] MemoryDimAlgoBase* getMemoryDimAlgo() const { return memoryDimAlgo.get(); };
    // void setMemoryDimAlgo(MemoryDimAlgo *a) { memoryDimAlgo = a; };

    // Tile binding and scheduling algorithm
    [[nodiscard]] TileBindingAlgoBase* getTileBindingAlgo() const { return tileBindingAlgo.get(); };
    // void setTileBindingAlgo(TileBindingAlgo *a) { tileBindingAlgo = a; };

    // Restrict the number of platform bindings generated by the tile binding
    // and scheduling algorithm
    [[nodiscard]] uint getMaxNrBindingsTileBindingAlgo() const { return maxNrBindingsTileBindingAlgo; };
    void setMaxNrBindingsTileBindingAlgo(const uint n) { maxNrBindingsTileBindingAlgo = n; };

    // Application graph
    [[nodiscard]] Graph* getApplicationGraph() const { return applicationGraph.get(); };

    // Platform graph
    [[nodiscard]] PlatformGraph* getPlatformGraph() const { return platformGraph.get(); };

    // Platform bindings
    [[nodiscard]] PlatformBindings* getPlatformBindings() const { return platformBindings.get(); };

    // State of flow
    FlowState getStateOfFlow() { return stateOfFlow; };

private:
    // State of the design flow
    void setNextStateOfFlow(FlowState s) { stateOfFlow = s; };

    // Output the SDF3 flow object as XML
    void outputAsXML(std::ostream &out);

protected:
    // Steps of the design flow
    void checkInputDesignFlow();
    void computeStorageDist();
    void selectStorageDist();
    void estimateStorageDist();
    void estimateBandwidthConstraint();
    void bindGraphToTiles();
    void estimateConnectionDelay();
    void constructTileSchedules();

    virtual void platformAwareTransform();
    // User interaction when running flow in step-by-step mode
    void handleUserInteraction();

    // Method for calculating size of binding on this platform
    [[nodiscard]] virtual BindingMethod platformBindingMethod() const {
        return BindingMethod(BindingMethod::Method::MaxOfScenarios);
    }

    void setMemoryDimAlgo(std::unique_ptr<MemoryDimAlgoBase> a) { memoryDimAlgo = std::move(a); }
    MemoryDimAlgoBase* getMemoryDimAlgo() { return memoryDimAlgo.get(); }

    void setTileBindingAlgo(std::unique_ptr<TileBindingAlgoBase> a) { tileBindingAlgo = std::move(a); }
    TileBindingAlgoBase* getTileBindingAlgo() { return tileBindingAlgo.get(); }

private:
    // Run flow step-by-step
    bool stepMode;

    // Application graph
    std::unique_ptr<Graph> applicationGraph;

    // Platform graph
    std::unique_ptr<PlatformGraph> platformGraph;

    // Platform bindings
    std::unique_ptr<PlatformBindings> platformBindings;

    // State of the design flow
    FlowState stateOfFlow;

    // Maximum number of platform bindings created in tile binding algorithm
    uint maxNrBindingsTileBindingAlgo;

    // Memory dimensioning object
    std::unique_ptr<MemoryDimAlgoBase> memoryDimAlgo;

    // Tile binding and scheduling object
    std::unique_ptr<TileBindingAlgoBase> tileBindingAlgo;
};

} // End namespace FSMSADF

#endif
